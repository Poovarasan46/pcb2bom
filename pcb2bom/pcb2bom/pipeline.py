"""End-to-end orchestration pipeline for pcb2bom.

Chains preprocessing, component detection, optical character recognition,
component catalog identification, and Bill of Materials export.
Also generates visual debug annotations on the output image.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Tuple, Union

import cv2
import numpy as np
import pandas as pd

from pcb2bom.bom import export_bom
from pcb2bom.detect import detect_components
from pcb2bom.lookup import run_lookup_pipeline
from pcb2bom.models import Component
from pcb2bom.ocr import run_ocr_pipeline
from pcb2bom.preprocess import preprocess_image

logger = logging.getLogger(__name__)

# Color mapping for annotations (BGR format)
CLASS_COLORS: Dict[str, Tuple[int, int, int]] = {
    "ic": (0, 165, 255),         # Orange
    "capacitor": (255, 144, 30),  # Blue
    "resistor": (34, 180, 34),    # Green
    "connector": (200, 50, 200),  # Purple
    "inductor": (0, 215, 255),    # Yellow
    "crystal": (255, 191, 0),     # Deep sky blue
    "diode": (0, 0, 220),         # Red
    "transistor": (180, 105, 255),# Pink
}


@dataclass
class PipelineConfig:
    """Configuration options for the pcb2bom pipeline run."""

    color_correction: str = "clahe"
    fix_glare: bool = True
    max_image_dim: int = 2048
    weights_path: Optional[Union[str, Path]] = None
    detection_confidence: float = 0.25
    use_mock_lookup: bool = True
    mock_db_path: Optional[Union[str, Path]] = None
    cache_dir: Optional[Union[str, Path]] = None
    output_dir: Union[str, Path] = Path("./output")


@dataclass
class PipelineResult:
    """Summary of all artifacts generated by the pipeline."""

    components: List[Component]
    unidentified_components: List[Component]
    bom_dataframe: pd.DataFrame
    csv_path: Path
    xlsx_path: Path
    annotated_image_path: Path
    debug_comparison_path: Optional[Path] = None


def draw_component_annotations(
    image: np.ndarray,
    components: List[Component],
    output_path: Union[str, Path],
) -> Path:
    """Renders bounding boxes, IDs, MPNs, and confidence badges onto the board photo.

    Args:
        image: BGR image.
        components: List of processed Component objects.
        output_path: Path where annotated image will be saved.

    Returns:
        Path to the saved annotated image.
    """
    annotated = image.copy()
    h, w = annotated.shape[:2]

    for comp in components:
        bbox = comp.bbox
        cls_name = comp.class_name.lower()
        color = CLASS_COLORS.get(cls_name, (0, 255, 0))

        # Status badge color for border
        status = comp.lookup_result.source if comp.lookup_result else "unidentified"
        border_thickness = 2
        if status == "unidentified" and cls_name not in ("resistor", "capacitor"):
            box_color = (0, 0, 255)  # Red for unidentified ICs
        else:
            box_color = color

        # Draw bounding rectangle
        cv2.rectangle(
            annotated,
            (bbox.xmin, bbox.ymin),
            (bbox.xmax, bbox.ymax),
            box_color,
            border_thickness,
        )

        # Build label text: e.g., "U1: NE555P [92%]"
        mpn_text = comp.lookup_result.matched_mpn if comp.lookup_result and comp.lookup_result.matched_mpn != "N/A" else ""
        if mpn_text and mpn_text != comp.id:
            label = f"{comp.id}: {mpn_text} ({int(comp.confidence * 100)}%)"
        else:
            label = f"{comp.id} {cls_name} ({int(comp.confidence * 100)}%)"

        # Background badge for legibility
        font = cv2.FONT_HERSHEY_SIMPLEX
        font_scale = 0.45
        thickness = 1
        (label_w, label_h), baseline = cv2.getTextSize(label, font, font_scale, thickness)

        label_ymin = max(bbox.ymin - 5, label_h + 5)
        badge_ymin = max(0, label_ymin - label_h - 4)
        badge_ymax = min(h, label_ymin + baseline + 2)
        badge_xmax = min(w, bbox.xmin + label_w + 6)

        cv2.rectangle(
            annotated,
            (bbox.xmin, badge_ymin),
            (badge_xmax, badge_ymax),
            box_color,
            -1,
        )
        cv2.putText(
            annotated,
            label,
            (bbox.xmin + 3, label_ymin - 2),
            font,
            font_scale,
            (255, 255, 255),
            thickness,
            cv2.LINE_AA,
        )

    out_file = Path(output_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(out_file), annotated)
    logger.info("Saved visual detection annotations to: %s", out_file)
    return out_file


def run_pipeline(
    image_path: Union[str, Path],
    config: Optional[PipelineConfig] = None,
) -> PipelineResult:
    """Executes the full pcb2bom end-to-end analysis on an input PCB image.

    Args:
        image_path: Path to the target PCB image.
        config: Optional PipelineConfig options.

    Returns:
        PipelineResult containing BoM table and output paths.
    """
    if config is None:
        config = PipelineConfig()

    out_dir = Path(config.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    logger.info("Starting pcb2bom pipeline on: %s", image_path)

    # 1. Preprocessing Stage
    debug_cmp_path = out_dir / "debug_preprocess_comparison.jpg"
    prep_res = preprocess_image(
        input_source=image_path,
        color_correction=config.color_correction,
        fix_glare=config.fix_glare,
        max_dim=config.max_image_dim,
        save_debug_to=debug_cmp_path,
    )
    processed_img = prep_res.processed

    # 2. Component Detection Stage
    components = detect_components(
        image=processed_img,
        weights_path=config.weights_path,
        confidence_threshold=config.detection_confidence,
    )

    # 3. OCR Stage
    components = run_ocr_pipeline(
        image=processed_img,
        components=components,
    )

    # 4. Catalog Lookup & Identification Stage
    components, unidentified = run_lookup_pipeline(
        components=components,
        use_mock=config.use_mock_lookup,
        mock_file_path=config.mock_db_path,
        cache_dir=config.cache_dir,
    )

    # 5. BoM Grouping and Export Stage
    csv_path, xlsx_path, df_bom = export_bom(
        components=components,
        output_dir=out_dir,
        base_name="bom",
    )

    # 6. Annotated Visual Render
    annotated_path = out_dir / "annotated_board.jpg"
    draw_component_annotations(
        image=processed_img,
        components=components,
        output_path=annotated_path,
    )

    logger.info(
        "pcb2bom pipeline completed successfully! %d parts cataloged, %d in BoM. Results saved in %s",
        len(components),
        len(df_bom),
        out_dir,
    )

    return PipelineResult(
        components=components,
        unidentified_components=unidentified,
        bom_dataframe=df_bom,
        csv_path=csv_path,
        xlsx_path=xlsx_path,
        annotated_image_path=annotated_path,
        debug_comparison_path=prep_res.saved_debug_path,
    )
